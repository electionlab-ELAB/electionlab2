create table if not exists public.el_favorability_polls (
 id bigint generated by default as identity primary key, pollster text not null, candidate text not null,
 state_code text not null default 'US', start_date date, end_date date not null,
 sample_size integer, population text, favorable_pct numeric not null, unfavorable_pct numeric not null,
 quality_weight numeric default 1, source_url text, status text not null default 'draft',
 constraint el_fav_pct check (favorable_pct between 0 and 100 and unfavorable_pct between 0 and 100));
create table if not exists public.el_issue_polls (
 id bigint generated by default as identity primary key, pollster text not null, issue text not null,
 question text not null, state_code text not null default 'US', start_date date, end_date date not null,
 sample_size integer, population text, results jsonb not null,
 quality_weight numeric default 1, source_url text, status text not null default 'draft');
alter table public.el_favorability_polls enable row level security;
alter table public.el_issue_polls enable row level security;
